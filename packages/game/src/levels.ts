/**
 * 传奇模式：10 个历史关卡。
 *
 * 设计原则（都是用户定的）：
 * - **显示真实日期。** 玩家是大学生不是股民，纪念性复盘比猜谜有价值（随机模式才藏日期）。
 * - **不代表"关键时刻"。** 入场那天看不出后面会发生什么 —— 所以每个关卡的开始日是
 *   事件前的第 8 个交易日，`briefing` 里只写**那一天公开能看到**的事，不许有后见之明。
 * - **`theme` 是这局的思考题**，写的是「该想什么」，不是「会涨还是跌」，
 *   所以提前看到不算剧透。
 *
 * 关卡窗口（`startDate` + `days`）全部落在真实交易日上：levels.test.ts 拿
 * data/history/level-<id>.json 里那份真实日历反过来校验，写错一天就会红。
 *
 * 简报有一条硬规矩，也有测试兜着：**只写入场那天公开可见的东西**。
 * 特别地，简报里不许出现「几月几日」—— 想写具体日期，通常就意味着在预报入场之后的事。
 *
 * 行情分片由 scripts/build-history-shards.ts 生成，见 docs/history-data.md。
 */

export interface ReplayLevel {
  /** 稳定 id，同时是分片文件名：history/level-<id>.json */
  id: string;
  /** 展示序号，1..10 */
  order: number;
  /** 关卡名。写成「那几天的样子」，不写事后评价 */
  title: string;
  /** 一句话背景，入场那天就能看到 */
  subtitle: string;
  /** 玩家入场的第一天（真实交易日） */
  startDate: string;
  /** 这局走多少个交易日 */
  days: number;
  /** 开局简报：**入场那天公开可见**的信息，逐条列出 */
  briefing: string[];
  /** 这局的思考题。不是预测，所以提前看到没关系 */
  theme: string;
}

