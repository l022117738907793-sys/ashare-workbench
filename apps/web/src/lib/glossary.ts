/**
 * 术语词典 —— 「没接触过股票的人看不懂的词」在这里各有一条解释。
 *
 * ## 为什么要内置，而不是问 AI
 *
 * 术语解释是这个站点里**唯一不能被生成模型碰**的内容：
 *   - 它解释的是规则，规则错了比没有解释更糟（「37 个测试全绿但规则是错的」这件事
 *     在这个项目里真发生过，见 packages/game/src/rules.ts 的注释）；
 *   - 历史推演里答错一句「什么是涨停」，可能顺手把后面的剧情说漏。
 * 所以每条都写死在代码里、随版本走，AI 只负责在**已审核的这条解释**之上补充追问。
 *
 * ## 写法
 *
 * `short` 是点一下就能看到的一句话，`full` 是「让交易员细讲」之后的话。
 * 语气照 交易员 的人设：自称「交易员」、用「您」称呼玩家、短句、克制、不夸张、
 * 不因虚拟盈利夸人、不因亏损责备人。
 *
 * `match` 只在词本身不足以定位时才写（比如「昨收」在正文里常写成「昨收价」）。
 */
