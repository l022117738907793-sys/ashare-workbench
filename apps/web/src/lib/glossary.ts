/** 按匹配文本长度降序，长的先试 —— 否则「可卖」会先把「可卖数量」切走 */
const SORTED: Array<{ key: string; term: Term }> = TERMS
  .flatMap((term) => [term.id, ...(term.alias ?? [])].map((key) => ({ key, term })))
  .sort((a, b) => b.key.length - a.key.length);

const BY_KEY = new Map(SORTED.map(({ key, term }) => [key, term]));

export function termByKey(key: string): Term | undefined {
  return BY_KEY.get(key);
}

export interface TermHit {
  /** 在原文里的起始下标 */
  index: number;
  key: string;
  term: Term;
}

/**
 * 找出文本里出现的术语。返回的是**位置**，不负责切分 —— 切分交给渲染层，
 * 这样它也能顺手处理「同一条解释、不同写法」。
 *
 * 同一位置只取最长的那个；已经吃掉的位置不再重复匹配。
 */
export function findTerms(text: string): TermHit[] {
  const taken: Array<[number, number]> = [];
  const hits: TermHit[] = [];
  for (const { key, term } of SORTED) {
    let from = 0;
    for (;;) {
      const index = text.indexOf(key, from);
      if (index < 0) break;
      from = index + 1;
      const end = index + key.length;
      if (taken.some(([s, e]) => index < e && end > s)) continue;
      taken.push([index, end]);
      hits.push({ index, key, term });
    }
  }
  return hits.sort((a, b) => a.index - b.index);
}

/**
 * 把一段文本切成「普通文字 / 术语」两种片段。
 *
 * 注意：只该用在**纯展示文本**上。术语本身会渲染成按钮，把它放进另一个
 * 按钮或链接里会得到嵌套的可交互元素，那是非法结构。
 */
export function splitTerms(text: string): Array<{ text: string; term?: Term }> {
  const hits = findTerms(text);
  if (hits.length === 0) return [{ text }];
  const parts: Array<{ text: string; term?: Term }> = [];
  let cursor = 0;
  for (const hit of hits) {
    if (hit.index > cursor) parts.push({ text: text.slice(cursor, hit.index) });
    parts.push({ text: hit.key, term: hit.term });
    cursor = hit.index + hit.key.length;
  }
  if (cursor < text.length) parts.push({ text: text.slice(cursor) });
  return parts;
}
